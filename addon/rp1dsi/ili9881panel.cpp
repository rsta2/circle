LOGMODULE ("ili9881c");

CILI9881Panel::CILI9881Panel (mipi_dsi_device *pDevice, CRPiPanel2Regulator *pRegulator)
:	m_pDevice (pDevice),
	m_pRegulator (pRegulator),
	m_PanelType (PanelUnknown),
	m_bInitialized (FALSE)
{
}

CILI9881Panel::~CILI9881Panel (void)
{
	if (m_bInitialized)
	{
		ili9881c_unprepare ();
	}
}

boolean CILI9881Panel::Initialize (TPanelType PanelType)
{
	assert (m_PanelType == PanelUnknown);
	m_PanelType = PanelType;
	assert (m_PanelType < PanelUnknown);

	if (ili9881c_prepare () < 0)
	{
		return FALSE;
	}

	m_bInitialized = TRUE;

	return TRUE;
}

const drm_display_mode *CILI9881Panel::GetDisplayMode (TPanelType PanelType)
{
	assert (PanelType < PanelUnknown);
	return panel_desc[PanelType].mode;
}

int CILI9881Panel::ili9881c_prepare (void)
{
	assert (m_pRegulator);
	if (!m_pRegulator->GPIOWrite (CRPiPanel2Regulator::LCD_RESET, 0))
	{
		LOGERR ("Cannot reset LCD");
		return -EIO;
	}
	msleep(20);

	if (!m_pRegulator->GPIOWrite (CRPiPanel2Regulator::LCD_RESET, 1))
	{
		LOGERR ("Cannot enable LCD");
		return -EIO;
	}
	msleep(20);

	assert (m_PanelType < PanelUnknown);
	const ili9881c_desc *desc = &panel_desc[m_PanelType];

	int ret;
	for (unsigned i = 0; i < desc->init_length; i++) {
		const struct ili9881c_instr *instr = &desc->init[i];

		if (instr->op == ILI9881C_SWITCH_PAGE)
			ret = ili9881c_switch_page(instr->arg.page);
		else if (instr->op == ILI9881C_COMMAND)
			ret = ili9881c_send_cmd_data(instr->arg.cmd.cmd,
						      instr->arg.cmd.data);

		if (ret)
			return ret;
	}

	ret = ili9881c_switch_page(0);
	if (ret)
		return ret;

	assert (m_pDevice);
	ret = mipi_dsi_dcs_set_tear_on(m_pDevice, MIPI_DSI_DCS_TEAR_MODE_VBLANK);
	if (ret)
		return ret;

	ret = mipi_dsi_dcs_exit_sleep_mode(m_pDevice);
	if (ret)
		return ret;

	// if (desc->flags & ILI9881_FLAGS_PANEL_ON_IN_PREPARE)
	{
		msleep(120);

		ret = mipi_dsi_dcs_set_display_on(m_pDevice);
	}

	return ret;
}

int CILI9881Panel::ili9881c_unprepare (void)
{
	assert (m_PanelType < PanelUnknown);
	const ili9881c_desc *desc = &panel_desc[m_PanelType];

	if (!(desc->flags & ILI9881_FLAGS_NO_SHUTDOWN_CMDS)) {
		assert (m_pDevice);

		// if (ctx->desc->flags & ILI9881_FLAGS_PANEL_ON_IN_PREPARE)
			mipi_dsi_dcs_set_display_off(m_pDevice);

		mipi_dsi_dcs_enter_sleep_mode(m_pDevice);
	}

	assert (m_pRegulator);
	m_pRegulator->GPIOWrite (CRPiPanel2Regulator::LCD_RESET, 0);

	return 0;
}

/*
 * The panel seems to accept some private DCS commands that map
 * directly to registers.
 *
 * It is organised by page, with each page having its own set of
 * registers, and the first page looks like it's holding the standard
 * DCS commands.
 *
 * So before any attempt at sending a command or data, we have to be
 * sure if we're in the right page or not.
 */
int CILI9881Panel::ili9881c_switch_page (u8 page)
{
	u8 buf[4] = { 0xff, 0x98, 0x81, page };
	int ret;

	assert (m_pDevice);
	ret = mipi_dsi_dcs_write_buffer(m_pDevice, buf, sizeof(buf));
	if (ret < 0)
		return ret;

	return 0;
}

int CILI9881Panel::ili9881c_send_cmd_data (u8 cmd, u8 data)
{
	u8 buf[2] = { cmd, data };
	int ret;

	assert (m_pDevice);
	ret = mipi_dsi_dcs_write_buffer(m_pDevice, buf, sizeof(buf));
	if (ret < 0)
		return ret;

	return 0;
}
